// Regenerates src/abi.ts from the Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../../contracts/out/DocumentaryCredit.sol/DocumentaryCredit.json", import.meta.url)));
